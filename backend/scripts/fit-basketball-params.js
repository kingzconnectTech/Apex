#!/usr/bin/env node
/**
 * scripts/fit-basketball-params.js
 *
 * Fits the three structural basketball parameters from REAL data and rewrites
 * the FITTED block of services/basketball/params.js:
 *
 *   1. homeCourtPoints   — per league, from TRAIN margin residuals only
 *                          (hca_fit = hca_structural + mean(actual - projected margin)).
 *                          The holdout is never used to pick a number.
 *   2. leagueMean        — the most recent COMPLETED season's actual per-team
 *                          possessions / ORtg / DRtg, pushed forward by the
 *                          capped drift in config.params.leagueMean. The
 *                          un-drifted season is kept as `baseline` (the
 *                          prior-season fallback). The runtime blend toward the
 *                          current season's observed means lives in params.js.
 *   3. sigma             — learned from MARKET-ANCHORED residuals
 *                          (actual ~ 1 + model + market fitted on TRAIN), with
 *                          minSamples, a blend weight and a 95% CI on the SD.
 *
 * Everything is fitted on the TRAIN partition of a walk-forward backtest: the
 * harness rates each team only from games that tipped off strictly earlier, and
 * closing lines are used only as benchmarks / anchors, never as model inputs.
 *
 * The script is READ-ONLY until --write; without it nothing is persisted and
 * params.js keeps its existing FITTED block.
 *
 * Usage:
 *   node scripts/fit-basketball-params.js --league=nba --seasons=2025,2026
 *   node scripts/fit-basketball-params.js --league=nba --seasons=2025,2026 --write
 *   node scripts/fit-basketball-params.js --league=nba,wnba --holdout=0.25 --out=fit.json
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const { resolveLeagueKey, LEAGUES } = require('../services/basketball/leagues');
const { evaluate } = require('../services/basketball/backtester');
const { sigmaFromResiduals } = require('../services/basketball/probability');
const { cappedDrift, setFittedParams } = require('../services/basketball/params');
const { loadSeasonDataset, splitHoldout } = require('./refit-basketball-calibrator');
const {
  ols, seasonAverages, marketMarginOf,
} = require('./diagnose-basketball-projection-bias');
const CONFIG = require('../services/basketball/config');

const PARAMS_PATH = path.join(__dirname, '..', 'services', 'basketball', 'params.js');
const BEGIN = '// === FITTED:BEGIN (generated by scripts/fit-basketball-params.js) ===';
const END = '// === FITTED:END ===';

// --------------------------------------------------------------------------
// Small helpers
// --------------------------------------------------------------------------

function clamp(v, lo, hi) {
  return Math.min(hi, Math.max(lo, v));
}

function round(v, dp = 2) {
  if (v == null || !Number.isFinite(v)) return null;
  return Number(v.toFixed(dp));
}

function mean(arr) {
  const v = (Array.isArray(arr) ? arr : []).filter(Number.isFinite);
  return v.length ? v.reduce((s, x) => s + x, 0) / v.length : null;
}

function sd(arr) {
  const v = (Array.isArray(arr) ? arr : []).filter(Number.isFinite);
  if (v.length < 2) return null;
  const m = mean(v);
  return Math.sqrt(v.reduce((s, x) => s + (x - m) * (x - m), 0) / (v.length - 1));
}

/** implied league total from a {possessions, ortg, drtg} mean. */
function impliedTotal(lm) {
  if (!lm || !Number.isFinite(lm.possessions) || !Number.isFinite(lm.ortg)) return null;
  return lm.possessions * ((lm.ortg + (Number.isFinite(lm.drtg) ? lm.drtg : lm.ortg)) / 100);
}

/** Split per-game rows at the pick-row cutoff (identical convention to the diagnostic). */
function splitGamesByCutoff(gameRows, cutoff) {
  const ts = cutoff ? new Date(cutoff).getTime() : Infinity;
  const train = [];
  const holdout = [];
  gameRows.forEach(g => {
    if (!g.tipoff) return;
    (new Date(g.tipoff).getTime() < ts ? train : holdout).push(g);
  });
  return { train, holdout };
}

const monthOf = (g) => (g.tipoff ? String(g.tipoff).slice(0, 7) : null);

/** Bias of a game set: mean(actual - projected) for total and margin. */
function projBias(games) {
  return {
    n: games.length,
    dTotal: mean(games.map(g => (Number.isFinite(g.actualTotal) && Number.isFinite(g.projTotal) ? g.actualTotal - g.projTotal : null))),
    dMargin: mean(games.map(g => (Number.isFinite(g.actualMargin) && Number.isFinite(g.projMargin) ? g.actualMargin - g.projMargin : null))),
    meanProjTotal: mean(games.map(g => g.projTotal)),
    meanActualTotal: mean(games.map(g => g.actualTotal)),
    meanProjMargin: mean(games.map(g => g.projMargin)),
    meanActualMargin: mean(games.map(g => g.actualMargin)),
  };
}

/**
 * Anchored-residual sigma for one target.
 * `actual ~ intercept + w_model * model + w_market * market` is fitted on the
 * TRAIN games that carry a closing line; the SAME fitted weights produce the
 * anchored projection for every game, and sigma is the SD of actual - anchored.
 */
function fitSigmaFor(target, trainGames) {
  const usable = trainGames.filter(g => g.closing && Number.isFinite(g.closing.total));
  const modelOf = (g) => (target === 'total' ? g.projTotal : g.projMargin);
  const marketOf = (g) => (target === 'total'
    ? (Number.isFinite(g.closing?.total) ? g.closing.total : null)
    : marketMarginOf(g));
  const actualOf = (g) => (target === 'total' ? g.actualTotal : g.actualMargin);

  const rows = usable.filter(g => Number.isFinite(modelOf(g)) && marketOf(g) != null && Number.isFinite(actualOf(g)));
  const fit = ols(rows.map(actualOf), rows.map(g => [modelOf(g), marketOf(g)]));
  if (!fit || rows.length < 3) {
    return { n: 0, sd: null, ci: null, fit: null, weightModel: null, weightMarket: null, anchored: null };
  }

  const anchored = rows.map(g => fit.coef[0] + fit.coef[1] * modelOf(g) + fit.coef[2] * marketOf(g));
  const residuals = rows.map((g, i) => actualOf(g) - anchored[i]);
  const sigma = sigmaFromResiduals(residuals);
  const se = sigma != null ? sigma / Math.sqrt(2 * (residuals.length - 1)) : null;
  return {
    n: residuals.length,
    sd: sigma,
    ci: se == null ? null : [sigma - 1.96 * se, sigma + 1.96 * se],
    fit,
    weightModel: fit.coef[1],
    weightMarket: fit.coef[2],
    anchored,
  };
}

/**
 * Walk each season INDEPENDENTLY and merge the results.
 *
 * The default walk is one continuous stream across the seasons we load, so a
 * team's log carries a full prior season across the off-season and the
 * opening-month projection is driven by decayed games rather than by the league
 * mean. Live, a team's log holds only its current-season games, so the opening
 * month is the one place the league mean dominates — walking per season is what
 * reproduces that, and it is the only fair way to read the opening-month table.
 */
function evaluateWalk(parts, opts) {
  const merged = { rows: [], gameRows: [], games: 0, picks: 0, noPickGames: 0, missingOdds: 0 };
  parts.forEach(p => {
    const ev = evaluate({ league: p.league, games: p.games }, opts);
    merged.rows.push(...ev.rows);
    merged.gameRows.push(...ev.gameRows);
    ['games', 'picks', 'noPickGames', 'missingOdds'].forEach(k => { merged[k] += ev[k] || 0; });
  });
  merged.rows.sort((a, b) => new Date(a.tipoff) - new Date(b.tipoff));
  merged.gameRows.sort((a, b) => new Date(a.tipoff) - new Date(b.tipoff));
  return merged;
}

// --------------------------------------------------------------------------
// Reporting
// --------------------------------------------------------------------------

const f2 = (v) => (v == null || !Number.isFinite(v) ? 'n/a' : v.toFixed(2));
const f3 = (v) => (v == null || !Number.isFinite(v) ? 'n/a' : v.toFixed(3));
const f4 = (v) => (v == null || !Number.isFinite(v) ? 'n/a' : v.toFixed(4));
const sign = (v, dp = 2) => (v == null || !Number.isFinite(v) ? 'n/a' : `${v >= 0 ? '+' : ''}${v.toFixed(dp)}`);
const ciText = (ci) => (!ci ? 'n/a' : `[${f2(ci[0])}, ${f2(ci[1])}]`);

function table(headers, rows) {
  const widths = headers.map((h, i) => Math.max(String(h).length, ...rows.map(r => String(r[i] ?? '').length)));
  const line = (cells) => cells.map((c, i) => String(c ?? '').padEnd(widths[i])).join('  ');
  return [
    line(headers),
    widths.map(w => '-'.repeat(w)).join('  '),
    ...rows.map(line),
  ].join('\n');
}

// --------------------------------------------------------------------------
// Fitting one league
// --------------------------------------------------------------------------

async function fitLeague(leagueKey, args, log) {
  const key = resolveLeagueKey(leagueKey);
  if (!key) throw new Error(`unknown league "${leagueKey}"`);
  const structural = LEAGUES[key]; // raw structural constants, independent of the FITTED block
  const holdoutFraction = args.holdout;

  const parts = [];
  for (const seasonYear of args.seasons) {
    // eslint-disable-next-line no-await-in-loop
    const part = await loadSeasonDataset({
      leagueCfg: structural, seasonYear, cacheDir: args.cacheDir,
      concurrency: args.concurrency, withOdds: true, logger: log,
    });
    if (part.games.length) parts.push(part);
  }
  const games = parts.flatMap(p => p.games).sort((a, b) => new Date(a.tipoff) - new Date(b.tipoff));
  if (!games.length) throw new Error(`no usable games for ${leagueKey}`);

  const dataset = { league: leagueKey, games };

  // ---- PASS 0: structural model (BEFORE) ----
  setFittedParams({});
  const ev0 = evaluate(dataset, { calibrate: false, cfg: CONFIG });
  const split0 = splitHoldout(ev0.rows, holdoutFraction);
  const games0 = splitGamesByCutoff(ev0.gameRows, split0.cutoff);
  const before = { train: projBias(games0.train), holdout: projBias(games0.holdout) };

  // ---- 1. HOME COURT: structural + TRAIN margin residual ----
  const h = CONFIG.params.homeCourt;
  const residual0 = before.train.dMargin ?? 0;
  const hcaPass0 = round(clamp(structural.homeCourtPoints + residual0, h.minPoints, h.maxPoints), 2);

  // ---- 2. LEAGUE MEANS: last completed season + capped drift ----
  const seasonStats = parts
    .slice()
    .sort((a, b) => a.seasonYear - b.seasonYear)
    .map(p => {
      const a = seasonAverages(p.games, structural);
      return {
        season: p.seasonYear,
        games: p.games.length,
        possessions: a.possPerTeamGame,
        ortg: a.ortg,
        drtg: a.ortg, // closed system: league ORtg == league DRtg
        avgTotal: a.avgTotal,
      };
    });
  const drift = cappedDrift(seasonStats, CONFIG);
  const last = seasonStats[seasonStats.length - 1];
  const baseline = last ? { possessions: round(last.possessions, 2), ortg: round(last.ortg, 2), drtg: round(last.drtg, 2) } : null;
  const fittedMean = baseline ? {
    possessions: round(baseline.possessions + drift.possessions, 2),
    ortg: round(baseline.ortg + drift.ortg, 2),
    drtg: round(baseline.drtg + drift.drtg, 2),
  } : null;

  // ---- PASS 1: with hca + leagueMean, refine hca and learn sigma ----
  const provisional = () => ({
    homeCourtPoints: hcaPass0,
    leagueMean: fittedMean,
    baseline,
    drift,
    seasons: args.seasons,
  });
  setFittedParams({ [leagueKey]: provisional() });
  const ev1 = evaluate(dataset, { calibrate: false, cfg: CONFIG });
  const split1 = splitHoldout(ev1.rows, holdoutFraction);
  const games1 = splitGamesByCutoff(ev1.gameRows, split1.cutoff);
  const residual1 = projBias(games1.train).dMargin ?? 0;
  const hcaFit = round(clamp(hcaPass0 + residual1, h.minPoints, h.maxPoints), 2);

  const sigmaTotal = fitSigmaFor('total', games1.train);
  const sigmaMargin = fitSigmaFor('margin', games1.train);
  const sigma = {
    total: sigmaTotal.sd == null ? null : round(sigmaTotal.sd, 2),
    margin: sigmaMargin.sd == null ? null : round(sigmaMargin.sd, 2),
    totalSamples: sigmaTotal.n,
    marginSamples: sigmaMargin.n,
  };

  const entry = {
    homeCourtPoints: hcaFit,
    leagueMean: fittedMean,
    baseline,
    drift,
    sigma,
    seasons: args.seasons,
    fittedAt: new Date().toISOString(),
  };

  // ---- PASS 2: final (AFTER) ----
  setFittedParams({ [leagueKey]: entry });
  const ev2 = evaluate(dataset, { calibrate: false, cfg: CONFIG });
  const split2 = splitHoldout(ev2.rows, holdoutFraction);
  const games2 = splitGamesByCutoff(ev2.gameRows, split2.cutoff);
  const after = { train: projBias(games2.train), holdout: projBias(games2.holdout) };

  // ---- PASS 3: cold-start walk (production-like) ----
  // Every season walked independently, so each one starts with EMPTY team logs
  // exactly as the live engine sees it. In the continuous walk above a team's log
  // holds a full prior season across the off-season, which leaves the league mean
  // with almost no weight at an opening month — this pass is where the league-mean
  // change is actually visible.
  setFittedParams({});
  const coldBefore = evaluateWalk(parts, { calibrate: false, cfg: CONFIG });
  setFittedParams({ [leagueKey]: entry });
  const coldAfter = evaluateWalk(parts, { calibrate: false, cfg: CONFIG });

  // Opening month of EACH season present: the first month that season's games
  // actually tip off in. Reporting one row per season means a specific month
  // (e.g. 2025-10) is visible even when several seasons share the dataset.
  const openingMonths = parts.map(p => {
    const ms = [...new Set(p.games.map(monthOf).filter(Boolean))].sort();
    return ms[0] || null;
  }).filter(Boolean);
  const openingMonth = openingMonths[0] || null;
  const openGames = (rows, month) => rows.filter(g => monthOf(g) === month);
  const openings = openingMonths.map(month => ({
    month,
    before: { train: projBias(openGames(games0.train, month)), holdout: projBias(openGames(games0.holdout, month)) },
    after: { train: projBias(openGames(games2.train, month)), holdout: projBias(openGames(games2.holdout, month)) },
  }));

  // Same opening months, but read off the COLD-START walk (production-like): each
  // season's first games have empty team logs, so the league mean is what moves
  // the projection.
  const coldOpenings = openingMonths.map(month => ({
    month,
    before: projBias(coldBefore.gameRows.filter(g => monthOf(g) === month)),
    after: projBias(coldAfter.gameRows.filter(g => monthOf(g) === month)),
  }));

  const report = {
    leagueKey,
    structural,
    entry,
    before,
    after,
    residualPass0: residual0,
    residualPass1: residual1,
    seasonStats,
    drift,
    sigmaTotal,
    sigmaMargin,
    openingMonth,
    openings,
    coldOpenings,
    ev: { games: ev0.games, picks: ev0.picks, noPickGames: ev0.noPickGames, missingOdds: ev0.missingOdds },
    split: split0,
    parts,
  };
  return report;
}

// --------------------------------------------------------------------------
// Rendering
// --------------------------------------------------------------------------

function render(report) {
  const out = [];
  const { structural, entry, before, after, seasonStats, drift } = report;

  out.push(`# Basketball parameter fit — ${structural.label} (${structural.key})`);
  out.push(`generated ${new Date().toISOString()}`);
  out.push('');
  out.push('## Data');
  report.parts.forEach(p => out.push(`  season ${p.seasonYear}: ${p.games.length} usable games${p.cached ? ' (cached)' : ''}`));
  out.push(`  games ${report.ev.games}   picks ${report.ev.picks}   no-pick games ${report.ev.noPickGames}   missing odds ${report.ev.missingOdds}`);
  out.push(`  train games ${before.train.n} -> holdout games ${before.holdout.n} starting ${report.split.cutoff || 'n/a'}`);
  out.push(`  opening month in the data: ${report.openingMonth}`);
  out.push('  Fitted on TRAIN only. The holdout columns are shown for reference and were never');
  out.push('  used to choose a value.');
  out.push('');

  // --- home court ---
  out.push('## 1. homeCourtPoints (TRAIN margin residuals only)');
  out.push(table(
    ['league', 'structural', 'TRAIN act-proj MGN (pass 0)', 'fitted', 'TRAIN act-proj MGN (after)', 'HOLDOUT before', 'HOLDOUT after'],
    [[
      structural.key, f2(structural.homeCourtPoints), sign(report.residualPass0),
      f2(entry.homeCourtPoints), sign(after.train.dMargin),
      sign(before.holdout.dMargin), sign(after.holdout.dMargin),
    ]],
  ));
  out.push(`  clamp: [${CONFIG.params.homeCourt.minPoints}, ${CONFIG.params.homeCourt.maxPoints}]  (config.params.homeCourt)`);
  out.push('');

  // --- league means ---
  out.push('## 2. leagueMean — last completed season + capped drift');
  out.push('  ACT columns are the season\'s real per-team-game possessions / ORtg and the implied total.');
  const meanRows = seasonStats.map(s => [
    String(s.season), f2(s.possessions), f2(s.ortg), f2(impliedTotal(s)),
  ]);
  meanRows.push(['structural', f2(structural.leagueMean.possessions), f2(structural.leagueMean.ortg), f2(impliedTotal(structural.leagueMean))]);
  if (entry.baseline) meanRows.push(['baseline (last season)', f2(entry.baseline.possessions), f2(entry.baseline.ortg), f2(impliedTotal(entry.baseline))]);
  if (entry.leagueMean) meanRows.push(['fitted (baseline+drift)', f2(entry.leagueMean.possessions), f2(entry.leagueMean.ortg), f2(impliedTotal(entry.leagueMean))]);
  out.push(table(['row', 'possessions', 'ortg', 'implied total'], meanRows));
  out.push(`  drift over last ${CONFIG.params.leagueMean.driftSeasons} seasons: possessions ${sign(drift.possessions)}  ortg ${sign(drift.ortg)}  drtg ${sign(drift.drtg)}  (n=${drift.n}${drift.capped ? ', CAPPED' : ''})`);
  out.push(`  caps (config.params.leagueMean): ${CONFIG.params.leagueMean.driftCapPossessions} possessions, ${CONFIG.params.leagueMean.driftCapPoints} points`);
  out.push('');

  // --- opening-month bias ---
  out.push(`## 3. Opening-month bias — before vs after (one row per season)`);
  const openRows = [];
  report.openings.forEach(o => {
    openRows.push([`${o.month} TRAIN`, o.before.train.n, sign(o.before.train.dTotal), sign(o.after.train.dTotal), sign(o.before.train.dMargin), sign(o.after.train.dMargin), f2(o.before.train.meanProjTotal), f2(o.after.train.meanProjTotal)]);
    openRows.push([`${o.month} HOLDOUT`, o.before.holdout.n, sign(o.before.holdout.dTotal), sign(o.after.holdout.dTotal), sign(o.before.holdout.dMargin), sign(o.after.holdout.dMargin), f2(o.before.holdout.meanProjTotal), f2(o.after.holdout.meanProjTotal)]);
  });
  out.push(table(
    ['set', 'games', 'act-proj TOT before', 'act-proj TOT after', 'act-proj MGN before', 'act-proj MGN after', 'proj TOT before', 'proj TOT after'],
    openRows,
  ));
  out.push('');
  out.push('## 3c. Opening-month bias on a COLD-START walk (production-like)');
  out.push('  Every season walked independently, so each season opens with EMPTY team logs —');
  out.push('  what the live engine sees. The continuous walk above keeps a full prior season');
  out.push('  in each log across the off-season, which leaves the league mean with almost no');
  out.push('  weight at an opening month. Train/holdout is not split here: these rows are');
  out.push('  reference only and never feed a fitted value.');
  out.push(table(
    ['set', 'games', 'act-proj TOT before', 'act-proj TOT after', 'act-proj MGN before', 'act-proj MGN after', 'proj TOT before', 'proj TOT after'],
    report.coldOpenings.map(o => [
      `${o.month} cold`, o.before.n,
      sign(o.before.dTotal), sign(o.after.dTotal),
      sign(o.before.dMargin), sign(o.after.dMargin),
      f2(o.before.meanProjTotal), f2(o.after.meanProjTotal),
    ]),
  ));
  out.push('');
  out.push('## 3b. Whole-window bias — before vs after');
  out.push(table(
    ['set', 'games', 'act-proj TOT before', 'act-proj TOT after', 'act-proj MGN before', 'act-proj MGN after'],
    [
      ['TRAIN', before.train.n, sign(before.train.dTotal), sign(after.train.dTotal), sign(before.train.dMargin), sign(after.train.dMargin)],
      ['HOLDOUT', before.holdout.n, sign(before.holdout.dTotal), sign(after.holdout.dTotal), sign(before.holdout.dMargin), sign(after.holdout.dMargin)],
    ],
  ));
  out.push('');

  // --- sigma ---
  out.push('## 4. sigma — learned from MARKET-ANCHORED TRAIN residuals');
  const ls = CONFIG.params.learnedSigma;
  const blendRow = (k, fit) => {
    const base = structural.sigma?.[k];
    const learned = entry.sigma?.[k];
    const n = entry.sigma?.[`${k}Samples`] ?? 0;
    const w = (Number.isFinite(learned) && n >= ls.minSamples)
      ? Math.min(ls.maxWeight, n / (n + ls.blendM))
      : 0;
    const applied = (w > 0 && Number.isFinite(base) && Number.isFinite(learned))
      ? round(base * (1 - w) + learned * w, 2)
      : base;
    return [
      k, f2(base), f2(learned), String(n), ciText(fit.ci), f3(w), f2(applied),
    ];
  };
  out.push(table(
    ['market', 'base', 'learned', 'n', 'learned 95% CI', 'blend w', 'applied'],
    [blendRow('total', report.sigmaTotal), blendRow('margin', report.sigmaMargin)],
  ));
  out.push(`  anchoring weights (TRAIN): total w_model ${f4(report.sigmaTotal.weightModel)}  w_market ${f4(report.sigmaTotal.weightMarket)}`);
  out.push(`                              margin w_model ${f4(report.sigmaMargin.weightModel)}  w_market ${f4(report.sigmaMargin.weightMarket)}`);
  out.push(`  blend = base*(1-w) + learned*w, w = min(maxWeight, n/(n+blendM)); minSamples ${ls.minSamples}, blendM ${ls.blendM}, maxWeight ${ls.maxWeight} (config.params.learnedSigma)`);
  out.push('');

  out.push('## Fitted block written to params.js');
  out.push(JSON.stringify({ [structural.key]: entry }, null, 2));
  out.push('');
  return out.join('\n');
}

// --------------------------------------------------------------------------
// Write the FITTED block back into params.js
// --------------------------------------------------------------------------

function writeFittedBlock(allFitted) {
  const src = fs.readFileSync(PARAMS_PATH, 'utf8');
  const begin = src.indexOf(BEGIN);
  const end = src.indexOf(END);
  if (begin < 0 || end < 0 || end < begin) throw new Error('FITTED markers not found in params.js');
  const body = `${BEGIN}\nlet FITTED = ${JSON.stringify(allFitted, null, 2)};\n`;
  const next = src.slice(0, begin) + body + src.slice(end);
  fs.writeFileSync(PARAMS_PATH, next);
  return next.length - src.length;
}

// --------------------------------------------------------------------------
// CLI
// --------------------------------------------------------------------------

function parseArgs(argv) {
  const args = { _: [] };
  argv.forEach(a => {
    const m = /^--([^=]+)(?:=(.*))?$/.exec(a);
    if (!m) { args._.push(a); return; }
    args[m[1]] = m[2] === undefined ? true : m[2];
  });
  return args;
}

async function main() {
  const argv = parseArgs(process.argv.slice(2));
  const leaguesInput = String(argv.league || 'nba').split(',').map(s => s.trim()).filter(Boolean);
  const args = {
    seasons: String(argv.seasons || '2025,2026').split(',').map(s => parseInt(s.trim(), 10)).filter(Number.isFinite),
    holdout: argv.holdout ? parseFloat(argv.holdout) : 0.25,
    cacheDir: argv.cache ? path.resolve(argv.cache) : path.join(os.tmpdir(), 'apex-calib'),
    concurrency: parseInt(argv.concurrency, 10) || 6,
  };
  const log = (msg) => process.stderr.write(`[fit] ${msg}\n`);

  const merged = {};
  const reports = [];

  for (const leagueKey of leaguesInput) {
    // eslint-disable-next-line no-await-in-loop
    const report = await fitLeague(leagueKey, args, log);
    reports.push(report);
    merged[leagueKey] = report.entry;
  }

  const out = [];
  reports.forEach(r => { out.push(render(r)); });
  if (reports.length > 1) {
    out.push('## Combined FITTED block');
    out.push(JSON.stringify(merged, null, 2));
    out.push('');
  }
  console.log(out.join('\n'));

  if (argv.out) {
    fs.writeFileSync(path.resolve(argv.out), JSON.stringify({
      generatedAt: new Date().toISOString(),
      seasons: args.seasons,
      leagues: reports.map(r => ({
        league: r.leagueKey,
        structural: {
          homeCourtPoints: r.structural.homeCourtPoints,
          leagueMean: r.structural.leagueMean,
          sigma: r.structural.sigma,
          priorSeason: r.structural.priorSeason,
        },
        fitted: r.entry,
        before: r.before,
        after: r.after,
        openingMonth: r.openingMonth,
        openings: r.openings,
        coldOpenings: r.coldOpenings,
        seasonStats: r.seasonStats,
        drift: r.drift,
        sigma: {
          total: { ...r.sigmaTotal, fit: undefined, anchored: undefined },
          margin: { ...r.sigmaMargin, fit: undefined, anchored: undefined },
        },
      })),
    }, null, 2));
    console.log(`\nWrote JSON to ${argv.out}`);
  }

  if (argv.write) {
    const delta = writeFittedBlock(merged);
    console.log(`\nWrote FITTED block to ${PARAMS_PATH} (${delta >= 0 ? '+' : ''}${delta} bytes).`);
  } else {
    console.log('\n(dry run — re-run with --write to persist the FITTED block into params.js)');
  }
}

