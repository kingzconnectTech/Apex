/**
 * Capped season-over-season drift, averaged over the last `driftSeasons` pairs.
 *
 * @param {Array<{season:number, possessions:number, ortg:number, drtg:number}>} seasons - ascending
 * @param {Object} cfg
 */
function cappedDrift(seasons, cfg) {
  const p = cfg?.params?.leagueMean || {};
  const capPoints = p.driftCapPoints ?? 1.5;
  const capPoss = p.driftCapPossessions ?? 1.5;
  const list = (Array.isArray(seasons) ? seasons : [])
    .filter(s => Number.isFinite(s?.ortg) && Number.isFinite(s?.possessions))
    .sort((a, b) => a.season - b.season);
  if (list.length < 2) {
    return { possessions: 0, ortg: 0, drtg: 0, n: 0, capped: false };
  }
  const n = Math.max(1, Math.min(p.driftSeasons ?? 2, list.length - 1));
  let dOrtg = 0;
  let dDrtg = 0;
  let dPoss = 0;
  for (let i = list.length - n; i < list.length; i++) {
    dOrtg += list[i].ortg - list[i - 1].ortg;
    dDrtg += (list[i].drtg ?? list[i].ortg) - (list[i - 1].drtg ?? list[i - 1].ortg);
    dPoss += list[i].possessions - list[i - 1].possessions;
  }
  dOrtg /= n;
  dDrtg /= n;
  dPoss /= n;
  const capped = Math.abs(dOrtg) > capPoints || Math.abs(dDrtg) > capPoints || Math.abs(dPoss) > capPoss;
  return {
    possessions: clamp(dPoss, -capPoss, capPoss),
    ortg: clamp(dOrtg, -capPoints, capPoints),
    drtg: clamp(dDrtg, -capPoints, capPoints),
    n,
    capped,
  };
}

/**
 * The league mean to shrink toward, for one game.
 *
 * base   = the most recent COMPLETED season's real per-team possessions/ORtg/DRtg
 *        + the capped drift above (i.e. a forward extrapolation of the last
 *        completed season, not of a hand-set constant);
 * blend  = the current season's OBSERVED league means, adopted with
 *        w = teamGames / (teamGames + currentBlendM). A small m adopts the live
 *        environment fast on purpose — the opening month is exactly where a
 *        stale league mean hurts most.
 *
 * @param {Object} leagueCfg
 * @param {Object} cfg
 * @param {Object|null} [observed] - { possessions, ortg, drtg, teamGames }
 * @returns {Object}
 */
function resolveLeagueMean(leagueCfg, cfg, { observed = null } = {}) {
  const structural = leagueCfg?.leagueMean || { possessions: 100, ortg: 110, drtg: 110 };
  const entry = fittedFor(leagueCfg, cfg);
  if (!entry?.leagueMean) {
    return { ...structural, source: 'structural', weight: 0, base: null, drift: null };
  }

  const p = cfg?.params?.leagueMean || {};
  const drift = entry.drift || { possessions: 0, ortg: 0, drtg: 0, n: 0 };
  const base = entry.leagueMean; // already includes the capped drift (baked at fit time)

  const projected = {
    possessions: base.possessions,
    ortg: base.ortg,
    drtg: base.drtg,
  };

  let weight = 0;
  if (observed && Number.isFinite(observed.possessions)) {
    const games = Number(observed.teamGames) || 0;
    if (games >= (p.minObservedTeamGames ?? 20)) {
      weight = games / (games + (p.currentBlendM ?? 8));
      projected.possessions = projected.possessions * (1 - weight) + observed.possessions * weight;
      if (Number.isFinite(observed.ortg)) projected.ortg = projected.ortg * (1 - weight) + observed.ortg * weight;
      if (Number.isFinite(observed.drtg)) projected.drtg = projected.drtg * (1 - weight) + observed.drtg * weight;
    }
  }

  return {
    possessions: round(projected.possessions, 2),
    ortg: round(projected.ortg, 2),
    drtg: round(projected.drtg, 2),
    source: weight > 0 ? 'fitted+observed' : 'fitted',
    weight: round(weight, 3),
    base: { possessions: base.possessions, ortg: base.ortg, drtg: base.drtg },
    drift,
  };
}

/** Home court, fitted per league from TRAIN margin residuals (clamped to config). */
function resolveHomeCourtPoints(leagueCfg, cfg) {
  const structural = leagueCfg?.homeCourtPoints ?? 0;
  const entry = fittedFor(leagueCfg, cfg);
  if (!entry || !Number.isFinite(entry.homeCourtPoints)) return structural;
  const h = cfg?.params?.homeCourt || {};
  return round(clamp(entry.homeCourtPoints, h.minPoints ?? 0.5, h.maxPoints ?? 5), 2);
}

/**
 * Sigma, blended from the structural base and the residual SD learned from
 * market-anchored residuals.
 *
 * weight = n / (n + blendM), capped at maxWeight, and only applied at all once
 * n >= minSamples. The blend (rather than a straight swap) is deliberate: one
 * season of residuals should move sigma materially without letting it detach
 * from the structural base.
 */
function resolveSigma(leagueCfg, cfg) {
  const base = leagueCfg?.sigma || { total: 17.5, margin: 11.5 };
  const entry = fittedFor(leagueCfg, cfg);
  const ls = cfg?.params?.learnedSigma || {};
  if (!entry?.sigma || ls.enabled === false) {
    return { ...base, learned: null };
  }

  const out = { ...base };
  const detail = {};
  ['total', 'margin'].forEach(k => {
    const learned = entry.sigma[k];
    const n = entry.sigma[`${k}Samples`] ?? 0;
    if (!Number.isFinite(learned) || n < (ls.minSamples ?? 150) || !Number.isFinite(base[k])) return;
    const w = Math.min(ls.maxWeight ?? 0.85, n / (n + (ls.blendM ?? 400)));
    out[k] = round(base[k] * (1 - w) + learned * w, 2);
    detail[k] = { learned, base: base[k], n, weight: round(w, 3) };
  });

  return { ...out, learned: Object.keys(detail).length ? detail : null };
}

/**
 * Current-season league means observed from real games, pooled over team-games.
 * `games` is any list of derived games (deriveGameMetrics output): the caller
 * passes the walk-forward logs, so nothing from the future can leak in.
 *
 * ORtg and DRtg are averaged per TEAM-GAME (each is already a per-team-game
 * rate), and possessions per team-game gives the pace. In a closed system the
 * league-average ORtg equals the league-average DRtg, so both are estimated
 * from the same points/possessions pool.
 *
 * @param {Array} games
 * @returns {{possessions:number|null, ortg:number|null, drtg:number|null, teamGames:number}}
 */
function observedLeagueMean(games) {
  const possessions = [];
  const ortg = [];
  const drtg = [];
  (Array.isArray(games) ? games : []).forEach(g => {
    if (!g) return;
    if (Number.isFinite(g.possessions) && g.possessions > 0) possessions.push(g.possessions);
    if (Number.isFinite(g.ortg)) ortg.push(g.ortg);
    if (Number.isFinite(g.drtg)) drtg.push(g.drtg);
  });
  return {
    possessions: mean(possessions),
    ortg: mean(ortg),
    drtg: mean(drtg),
    teamGames: possessions.length,
  };
}

/**
 * Overlay the fitted parameters onto a league config.
 *
 * Returns the config unchanged (same object) when params are disabled or the
 * league has no fitted block, so callers never have to branch on it.
 *
 * @param {Object} leagueCfg - getLeagueConfig() output
 * @param {Object} cfg       - basketball config
 * @param {Object} [opts]
 * @param {Object|null} [opts.observed] - observedLeagueMean() output
 * @returns {Object}
 */
function applyParams(leagueCfg, cfg, { observed = null } = {}) {
  const entry = fittedFor(leagueCfg, cfg);
  if (!entry) return leagueCfg;

  const lm = resolveLeagueMean(leagueCfg, cfg, { observed });
  const sigma = resolveSigma(leagueCfg, cfg);

  return {
    ...leagueCfg,
    homeCourtPoints: resolveHomeCourtPoints(leagueCfg, cfg),
    leagueMean: { possessions: lm.possessions, ortg: lm.ortg, drtg: lm.drtg },
    // The prior-season fallback is the LAST COMPLETED season's real averages (no
    // drift): a team we know nothing else about is best described by what it
    // actually did, not by an extrapolation.
    priorSeason: entry.baseline
      ? { ortg: entry.baseline.ortg, drtg: entry.baseline.drtg, pace: entry.baseline.possessions }
      : leagueCfg.priorSeason,
    sigma: { total: sigma.total, margin: sigma.margin },
    paramsMeta: {
      homeCourtPoints: resolveHomeCourtPoints(leagueCfg, cfg),
      leagueMean: lm,
      sigma: {
        total: sigma.total,
        margin: sigma.margin,
        learned: sigma.learned || null,
        base: { total: leagueCfg.sigma?.total ?? null, margin: leagueCfg.sigma?.margin ?? null },
      },
      fittedAt: entry.fittedAt || null,
    },
  };
}

