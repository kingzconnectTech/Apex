/**
 * basketball/params.js
 *
 * Fitted per-league parameters and the resolvers that apply them.
 *
 * WHY THIS EXISTS
 * The structural constants in leagues.js (leagueMean, priorSeason, sigma, and
 * homeCourtPoints) were hand-set. Measured against real seasons they are wrong
 * in two ways that both push the opening month off:
 *
 *   - the league mean is anchored to a stale scoring environment, so early in a
 *     season (when every team's rating is still shrunk toward it) the projection
 *     is biased low;
 *   - the margin sigma is materially smaller than a real residual, so stated
 *     probabilities are overconfident.
 *
 * This module holds the values fitted from real data (see
 * scripts/fit-basketball-params.js) and the resolvers that turn them into a
 * per-game league config:
 *
 *   resolveLeagueMean      previous season's ACTUAL possessions / ORtg / DRtg,
 *                          pushed forward by a CAPPED two-season drift, then
 *                          blended quickly toward the current season's observed
 *                          league means.
 *   resolveHomeCourtPoints fitted per league from TRAIN margin residuals only.
 *   resolveSigma           learned from market-anchored residuals, blended with
 *                          the structural base and clamped.
 *   applyParams            one call that returns a league config with all three
 *                          overlaid (the structural values stay as the fallback
 *                          for any league without a fitted block).
 *
 * Every cap, blend rate and minimum sample lives in config.params — this file
 * only holds numbers and the maths that uses them.
 *
 * R5 still holds: learned sigma is a property of the GAME, never of how much we
 * know about it. Data quality continues to flow only to the confidence tier.
 */

